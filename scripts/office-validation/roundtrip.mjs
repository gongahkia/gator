import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { inspectOffice, editOffice } from "../../app-host/src/office.mjs";

const directory = process.argv[2];
if (!directory) throw new Error("Usage: node roundtrip.mjs fixture-directory");
const original = await readFile(join(directory, "rich-template.pptx"));
const before = inspectOffice("pptx", original);
assert.equal(before.slides[0].shapes[1].paragraphs.length, 3);
const value = "Edited through the shared file editor.\nSecond line\tSummary 🐊";
const updated = editOffice("pptx", original, { paragraphs: { "s:0:p:1": value } });
const after = inspectOffice("pptx", updated);
assert.equal(after.slides[0].shapes[1].paragraphs[0].text, value);
assert.equal(after.slides[0].shapes[1].paragraphs[0].runs.map(run => run.text).join(""), value);
assert.equal(after.slides[0].shapes[1].paragraphs[1].text, before.slides[0].shapes[1].paragraphs[1].text);
await writeFile(join(directory, "host-roundtrip.pptx"), updated);
const docOriginal = await readFile(join(directory, "professional-new.docx"));
const docBefore = inspectOffice("docx", docOriginal);
const paragraph = docBefore.blocks.find(block => block.type === "paragraph" && block.text.startsWith("Availability"));
assert.ok(paragraph.text.includes("\n") && paragraph.text.includes("\t"));
const docUpdated = editOffice("docx", docOriginal, { paragraphs: { [paragraph.id]: value } });
const docAfter = inspectOffice("docx", docUpdated);
assert.equal(docAfter.blocks.find(block => block.id === paragraph.id).text, value);
assert.deepEqual(docAfter.blocks.find(block => block.type === "table"), docBefore.blocks.find(block => block.type === "table"));
await writeFile(join(directory, "host-roundtrip.docx"), docUpdated);

const bookOriginal = await readFile(join(directory, "professional-new.xlsx"));
const bookUpdated = editOffice("xlsx", bookOriginal, { cells: { "0!B2": "150", "0!B4": "=SUM(B2:B3)" } });
const cells = inspectOffice("xlsx", bookUpdated).sheets[0].cells;
assert.equal(cells.find(cell => cell.address === "B2").value, "150");
assert.equal(cells.find(cell => cell.address === "B4").formula, "SUM(B2:B3)");
assert.equal(cells.find(cell => cell.address === "B4").value, "");
await writeFile(join(directory, "host-roundtrip.xlsx"), bookUpdated);
console.log("Shared DOCX/XLSX/PPTX editor roundtrips passed; validate the saved packages with Open XML SDK.");
