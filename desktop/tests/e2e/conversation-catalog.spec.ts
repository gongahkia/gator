import { _electron as electron, test, expect } from "@playwright/test";
import { createServer } from "node:http";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { closeDesktop, temporaryDirectory } from "./lifecycle";

test("indexed history searches old messages and retains reversible organization across restart", async () => {
  test.setTimeout(120000);
  const directory = await temporaryDirectory(join(tmpdir(), "gator-catalog-e2e-"));
  const workspace = join(directory, "workspace"), config = join(directory, "config/gator");
  await mkdir(workspace); await mkdir(config, { recursive: true });
  let providerCalls = 0;
  const server = createServer((_req, res) => { providerCalls++; res.writeHead(500); res.end("This test must not call a model"); });
  await new Promise<void>(done => server.listen(0, "127.0.0.1", done));
  await writeFile(join(config, "config.json"), JSON.stringify({ version: 4, defaults: { provider: "fixture", model: "fixture" }, custom_providers: [{ id: "fixture", base_url: `http://127.0.0.1:${(server.address() as { port: number }).port}`, models: ["fixture"], default_model: "fixture" }] }), { mode: 0o600 });
  const at = Date.now();
  const oldID = "work-catalog-129", oldRoot = join(directory, "state/gator/conversations", oldID);
  for (let index = 0; index < 130; index++) {
    const id = `work-catalog-${String(index).padStart(3, "0")}`, root = join(directory, "state/gator/conversations", id);
    await mkdir(join(root, "revisions"), { recursive: true });
    await writeFile(join(root, "conversation.json"), JSON.stringify({ version: 2, id, title: `Topic ${index}`, source_path: workspace, snapshot_id: "snap-catalog", head_revision_id: index === 129 ? "rev-old" : undefined, created_at: new Date(at - 86400000 * 10).toISOString(), updated_at: new Date(at - index * 60000).toISOString() }));
  }
  const retained = { version: 2, id: "rev-old", conversation_id: oldID, snapshot_id: "snap-catalog", objective: "Choose a direction", bundle_path: join(directory, "missing-result"), status: "completed", final_text: "We chose the jade orchid decision for the garden.", created_at: new Date(at - 129 * 60000).toISOString() };
  await writeFile(join(oldRoot, "revisions/rev-old.json"), JSON.stringify(retained));
  const original = await readFile(join(oldRoot, "revisions/rev-old.json"));
  const env = Object.fromEntries(Object.entries({ ...process.env, GATOR_INTERNAL_COMMANDS: "", GATOR_STATE_DIR: join(directory, "state"), GATOR_CONFIG_DIR: join(directory, "config"), GATOR_DESKTOP_USER_DATA: join(directory, "desktop"), GATOR_DESKTOP_WORKSPACE: workspace }).filter((entry): entry is [string, string] => typeof entry[1] === "string"));
  const executablePath = process.env.GATOR_DESKTOP_TEST_EXECUTABLE;
  const launch = () => electron.launch({ executablePath, args: executablePath ? [] : ["."], cwd: resolve("."), env });
  let app = await launch();
  try {
    let page = await app.firstWindow();
    await expect(page.getByRole("textbox", { name: "Message Gator", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "All conversations", exact: true }).click();
    let browser = page.getByRole("region", { name: "Conversations", exact: true });
    await expect(browser.locator("[data-chat-row]")).toHaveCount(50);
    await browser.getByRole("button", { name: "Next", exact: true }).click();
    await expect(browser.getByText("Page 2", { exact: true })).toBeVisible();
    await expect(browser.locator("[data-chat-row]")).toHaveCount(50);
    await browser.getByRole("button", { name: "Next", exact: true }).click();
    await expect(browser.getByText("Page 3", { exact: true })).toBeVisible();
    await expect(browser.getByRole("button", { name: "Next", exact: true })).toBeDisabled();
    await browser.getByRole("button", { name: "Previous", exact: true }).click();
    await expect(browser.getByText("Page 2", { exact: true })).toBeVisible();
    let search = browser.getByRole("searchbox", { name: "Search conversations" });
    await search.fill("jade orchid");
    await expect(browser.getByRole("button", { name: "Open conversation: Topic 129", exact: true })).toBeVisible();
    await expect(browser.locator("[data-chat-row]")).toHaveCount(1);
    await expect(browser.getByText("Page 1", { exact: true })).toBeVisible();
    await expect(browser.locator(".catalog-snippet mark")).toHaveText("jade orchid");
    await browser.getByRole("button", { name: "Manage conversation: Topic 129", exact: true }).click();
    await page.locator(".catalog-row-menu").getByRole("button", { name: "Rename", exact: true }).click();
    await browser.getByRole("textbox", { name: "Conversation title" }).fill("Garden plans");
    await browser.getByRole("button", { name: "Save title", exact: true }).click();
    await expect(browser.getByRole("button", { name: "Open conversation: Garden plans", exact: true })).toBeVisible();
    await browser.getByRole("button", { name: "Manage conversation: Garden plans", exact: true }).click();
    await page.locator(".catalog-row-menu").getByRole("button", { name: "Pin", exact: true }).click();
    await expect(browser.getByRole("region", { name: "Pinned conversations" })).toBeVisible();
    await browser.getByRole("button", { name: "Manage conversation: Garden plans", exact: true }).click();
    await page.locator(".catalog-row-menu").getByRole("button", { name: "Archive", exact: true }).click();
    await expect(browser.getByRole("button", { name: "Open conversation: Garden plans", exact: true })).toHaveCount(0);
    await browser.getByRole("button", { name: "Archived", exact: true }).click();
    await expect(browser.getByRole("button", { name: "Open conversation: Garden plans", exact: true })).toBeVisible();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(760, 560));
	 await page.evaluate(() => new Promise<void>(done => requestAnimationFrame(() => requestAnimationFrame(() => done()))));
    await browser.getByRole("button", { name: "Manage conversation: Garden plans", exact: true }).click();
    const menuBox = await page.locator(".catalog-row-menu").boundingBox();
    expect(menuBox && menuBox.x >= 0 && menuBox.y >= 0 && menuBox.x + menuBox.width <= 760 && menuBox.y + menuBox.height <= 560).toBe(true);
    await page.screenshot({ path: "test-results/catalog-dark-compact.png", animations: "disabled" });
    await page.keyboard.press("Escape");
    await expect(browser.getByRole("button", { name: "Manage conversation: Garden plans", exact: true })).toBeFocused();
    await browser.getByRole("button", { name: "Manage conversation: Garden plans", exact: true }).click();
    await page.locator(".catalog-row-menu").getByRole("button", { name: "Restore to active chats", exact: true }).click();
    await browser.getByRole("button", { name: "Active", exact: true }).click();
    await expect(browser.getByRole("button", { name: "Open conversation: Garden plans", exact: true })).toBeVisible();
    expect(await readFile(join(oldRoot, "revisions/rev-old.json"))).toEqual(original);
    expect(JSON.parse(await readFile(join(oldRoot, "conversation.json"), "utf8")).head_revision_id).toBe("rev-old");
    await page.getByRole("button", { name: "Settings", exact: true }).click();
    await page.getByRole("button", { name: "Appearance settings", exact: true }).click();
    await page.getByRole("button", { name: /^Light / }).click();
    await page.getByRole("button", { name: "Back to app", exact: true }).click();
    await page.getByRole("button", { name: "All conversations", exact: true }).click();
    browser = page.getByRole("region", { name: "Conversations", exact: true });
    search = browser.getByRole("searchbox", { name: "Search conversations" });
    await search.fill("jade orchid");
    await expect(browser.getByRole("button", { name: "Open conversation: Garden plans", exact: true })).toBeVisible();
    await expect(browser).toHaveAttribute("aria-busy", "false");
    await page.screenshot({ path: "test-results/catalog-light-compact.png", animations: "disabled" });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await browser.getByRole("button", { name: "Manage conversation: Garden plans", exact: true }).click();
    await page.locator(".catalog-row-menu").getByRole("button", { name: "Rename", exact: true }).click();
    await browser.getByRole("textbox", { name: "Conversation title" }).fill("Keep this uncommitted title");
    const displayPath = join(oldRoot, "display.json"), display = JSON.parse(await readFile(displayPath, "utf8"));
    await writeFile(displayPath, JSON.stringify({ ...display, revision: display.revision + 1 }));
    await browser.getByRole("button", { name: "Refresh conversations", exact: true }).click();
    await expect(browser.getByText("This list changed. Cancel and choose the conversation again.", { exact: true })).toBeVisible();
    await expect(browser.getByRole("textbox", { name: "Conversation title" })).toHaveValue("Keep this uncommitted title");
    await expect(browser.getByRole("button", { name: "Save title", exact: true })).toBeDisabled();
    await browser.getByRole("button", { name: "Cancel", exact: true }).click();
    await browser.getByRole("button", { name: "Open conversation: Garden plans", exact: true }).click();
    await expect(page.getByText(retained.final_text, { exact: true })).toBeVisible();
    await closeDesktop(app); app = await launch(); page = await app.firstWindow();
    await expect(page.getByRole("region", { name: "Recent conversations", exact: true }).getByRole("button", { name: "Open conversation: Garden plans", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "All conversations", exact: true }).click();
    browser = page.getByRole("region", { name: "Conversations", exact: true });
    await browser.getByRole("searchbox", { name: "Search conversations" }).fill("jade orchid");
    await expect(browser.getByRole("region", { name: "Pinned conversations" }).getByRole("button", { name: "Open conversation: Garden plans", exact: true })).toBeVisible();
    expect((await readFile(join(directory, "state/gator/cache/conversations-v1.sqlite"))).subarray(0, 16).toString()).toBe("SQLite format 3\0");
    expect(providerCalls).toBe(0);
  } finally {
    await closeDesktop(app).catch(() => {});
    server.closeAllConnections(); await new Promise<void>(done => server.close(() => done()));
    await rm(directory, { recursive: true, force: true });
  }
});
