    const messages: BackendMessage[] = Array.from({ length: 50 }, (_, index) => ({ role: index % 2 ? "Gator" : "You", text: `Message ${index}. Keep the surrounding context and reading position.\n\nA second paragraph makes this a scrollable conversation.` }));
    messages.push({ role: "Deliverables", text: "", bundle: earlier });
    const state: BackendState = { ...snapshot.state!, home: false, title: "Offsite planning", conversation_id: "work-details-conversation", messages, work_details: { mode: "auto", snapshot_id: "snap-offsite", attachments: ["budget.md"], connector_ids: ["next-calendar"], latest_bundle: failed } };
    const publish = async (value: BackendState) => application.evaluate(({ BrowserWindow }, state) => BrowserWindow.getAllWindows()[0].webContents.send("gator:update", state), { ...snapshot, state: value });
    await publish(state);
    await composer.fill("Keep my unsent follow-up");
    const scroll = page.locator(".conversation-scroll");
    await scroll.evaluate((element) => { element.scrollTop = 0; });
    await page.getByRole("button", { name: "Show work details" }).click();
    const rail = page.getByRole("complementary", { name: "Work details", exact: true });
    await expect(rail).toBeVisible();
    const outputs = rail.getByRole("region", { name: "Outputs", exact: true });
    await expect(outputs.locator(".work-output")).toHaveCount(5);
    await page.evaluate(async () => { await Promise.allSettled(document.getAnimations().filter((animation) => animation.effect?.getComputedTiming().iterations !== Infinity).map((animation) => animation.finished)); });
    await page.screenshot({ path: "test-results/desktop-work-details-compact.png" });
    await expect(rail.getByRole("region", { name: "Follow-up checks", exact: true })).toHaveCount(0);
    await rail.getByRole("button", { name: /^Context/ }).click();
    await expect(rail.getByText("budget.md", { exact: true })).toBeVisible();
    await expect(rail.getByText("notes/venue.md", { exact: true })).toBeVisible();
    await expect(rail.getByText("Not measured", { exact: true })).toBeVisible();
